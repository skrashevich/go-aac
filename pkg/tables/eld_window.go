// LowDelaySynthesis480 returns the 1440-coefficient low-delay synthesis
// window for ELD 480-sample frames, converted from Q31 fixed-point to float32.
func LowDelaySynthesis480() []float32 {
	result := make([]float32, 1440)
	const scale = float32(1 << 31)
	for i, v := range ldWin480Raw {
		result[i] = float32(v) / scale
	}
	return result
}
